<?php

namespace Jponchiroli\LaravelBase\Console;

use Illuminate\Console\Command;
use Illuminate\Filesystem\Filesystem;
use Illuminate\Support\Str;
use Jponchiroli\LaravelBase\Docs\OpenApiBuilder;

class DomainDocsCommand extends Command
{
    protected $signature = 'domain:docs {name? : Entity name, e.g. Post. Omit to generate every domain}';

    protected $description = 'Regenerate the OpenAPI class of a domain from its Requests and table columns';

    public function handle(Filesystem $files): int
    {
        $names = $this->argument('name')
            ? [Str::studly((string) $this->argument('name'))]
            : $this->domains();

        $failed = false;
        $written = 0;

        foreach ($names as $name) {
            if (! preg_match('/^[A-Z][A-Za-z0-9]*$/', $name)) {
                $this->error("Invalid name: {$name}");

                return self::FAILURE;
            }

            $path = OpenApiBuilder::domainPath($name);
            $builder = new OpenApiBuilder;

            if ($error = $builder->domainError($name)) {
                $this->error($error);
                $failed = true;

                continue;
            }

            $builder->ensureBase($files, $name);
            $files->ensureDirectoryExists(dirname($path));
            $files->put($path, $builder->domainSource($name));

            $this->info("Updated: {$path}");
            $written++;

            foreach ($builder->warnings as $warning) {
                $this->warn($warning);
            }
        }

        $builder = new OpenApiBuilder;

        if ($written && $builder->writeJson($files)) {
            $this->info('Updated: '.OpenApiBuilder::jsonPath());
        }

        foreach ($builder->warnings as $warning) {
            $this->warn($warning);
        }

        return $failed ? self::FAILURE : self::SUCCESS;
    }

    /**
     * Every domain generated by make:domain, recognised by its Store request, plus any existing docs class.
     *
     * @return list<string>
     */
    protected function domains(): array
    {
        $requests = array_map(fn (string $file) => basename($file, 'StoreRequest.php'), glob(app_path('Http/Requests/*/*StoreRequest.php')) ?: []);
        $docs = array_map(fn (string $file) => basename($file, 'Docs.php'), glob(OpenApiBuilder::domainPath('*')) ?: []);

        return array_values(array_unique([...$requests, ...$docs]));
    }
}
